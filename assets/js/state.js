/**
 * 共享可变状态：单页里唯一的一份真相。
 *
 * 为什么集中：输入（摇杆/键盘）、下发（20 Hz 定时器）、渲染（状态帧）、
 * 兜底轮询（REST）四个方向都要读写同一批值。拆模块后如果各自持有副本，
 * 就会出现"界面显示已锁定、实际还在下发"这类不一致。
 *
 * 约定：
 *   - 这里只放数据，不放 DOM、不放定时器、不放网络对象；
 *   - 写状态的地方负责同步调用对应的渲染函数（显式，不用订阅回调），
 *     这样调用顺序在代码里看得见，调试时不必猜谁先谁后。
 */

import { LIMITS_DEFAULT } from "./config.js";

export const state = {
  /** 摇杆/键盘归一化后的指令，px ∈ [-1,1] 向右为正，py ∈ [-1,1] 向上为正。 */
  px: 0,
  py: 0,

  /** 急停锁存，镜像后端 PAUSED。必须显式解除。 */
  locked: false,

  /** 速度上限，首帧状态到达前用常量兜底。 */
  limits: { ...LIMITS_DEFAULT },

  /** 上一帧已下发的指令，用于"只在变化时发"。 */
  lastSent: { linear: 0, angular: 0 },

  /** 最近一次收到 socket 状态帧的时刻（performance.now）。 */
  lastSocketAt: 0,

  /** 本地刚点过急停/解除，此时间点之前忽略服务端 paused 回声。 */
  lockEchoUntil: 0,
};
